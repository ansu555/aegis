#!/usr/bin/env python3
"""Generate SimKeys.kt: the keys behind the simulated EMV card used by the
Kotlin tests (it is not part of the app).

The card's own (ICC) key is the same 1024-bit test key as the Rust
TestCard. On top of it sits a test certificate chain, a made-up CA and
issuer, so the real card-reading code (certificate recovery, static data
hash, DDA / fDDA / CDA signing) runs against it in tests. All private keys
here are public on purpose.

    python3 tools/gen_sim_card_keys.py > android/core/src/test/kotlin/app/tapvault/core/SimKeys.kt
"""

import os
import random
import sys

sys.path.insert(0, os.path.dirname(__file__))
import gen_test_card as g  # noqa: E402


def keypair(bits, e, seed):
    g.rng.seed(seed)
    while True:
        p, q = g.prime(bits // 2, e), g.prime(bits // 2, e)
        n = p * q
        nb = (n.bit_length() + 7) // 8
        if p != q and n.bit_length() == bits and n.to_bytes(nb, "big")[0] > 0x6A:
            return n, pow(e, -1, (p - 1) * (q - 1))


def small_icc():
    # Same sequence as gen_test_card.py's first key.
    g.rng.seed(0x7A9CA4D)
    while True:
        p, q = g.prime(512, 3), g.prime(512, 3)
        n = p * q
        nb = (n.bit_length() + 7) // 8
        if p != q and n.bit_length() == 1024 and n.to_bytes(nb, "big")[0] > 0x6A:
            return n, pow(3, -1, (p - 1) * (q - 1))


def main():
    icc_n, icc_d = small_icc()
    ca_n, ca_d = keypair(1408, 3, 0xCA0001)
    iss_n, iss_d = keypair(1152, 3, 0x155001)
    out = [
        "package app.tapvault.core",
        "",
        "// Generated by tools/gen_sim_card_keys.py. Test keys; private halves are public.",
        "internal object SimKeys {",
    ]
    for name, (n, d) in (("ICC", (icc_n, icc_d)), ("CA", (ca_n, ca_d)), ("ISSUER", (iss_n, iss_d))):
        nb = (n.bit_length() + 7) // 8
        out.append(f'    const val {name}_N = "{n:x}"')
        out.append(f'    const val {name}_D = "{d:0{nb * 2}x}"')
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
